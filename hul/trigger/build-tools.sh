#!/usr/bin/env bash
# Build the HUL trigger control programs (Register, NimIO, Debug, ReconfigFPGA) from the
# hul-trigger submodule (hul/trigger/hul-trigger, jparc-saphire/hul-trigger at the pinned commit).
#
# The upstream programs take the board address from include/TargetIP.hh at compile
# time. This script copies software/ of the submodule (Makefile, src, include) to the
# output directory, generates that header from HUL_TRIGGER_IP, and builds there, so the
# address stays in the host configuration and the submodule stays clean. Rebuild after
# changing the address.
#
# Host side only: nothing here talks to a board.
#
# Usage: HUL_TRIGGER_IP=<board IPv4> build-tools.sh [out-dir]
#   (normally: set -a; . config/local/hul-trigger.env; set +a)
#   out-dir defaults to hul/trigger/software (ignored by Git)
#   result: <out-dir>/bin/*, <out-dir>/build-info.json
# Needs: make, a C++17 compiler, zlib headers; the submodule
#   (git submodule update --init hul/trigger/hul-trigger).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
src="${here}/hul-trigger"
out="${1:-${here}/software}"
ip="${HUL_TRIGGER_IP:?HUL_TRIGGER_IP is not set (see config/hul-trigger.env.example)}"
if ! [[ "${ip}" =~ ^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})$ ]] ||
   (( BASH_REMATCH[1] > 255 || BASH_REMATCH[2] > 255 || BASH_REMATCH[3] > 255 || BASH_REMATCH[4] > 255 )); then
  echo "#E: HUL_TRIGGER_IP is not an IPv4 address: ${ip}" >&2; exit 2
fi

if [[ ! -f "${src}/software/Makefile" ]]; then
  echo "#E: ${src} is empty; run: git submodule update --init hul/trigger/hul-trigger" >&2; exit 4
fi
if [[ -n "$(git -C "${src}" status --porcelain)" ]]; then
  echo "#E: ${src} has local changes; refusing to build an unpinned tree" >&2; exit 4
fi
commit="$(git -C "${src}" rev-parse HEAD)"
pinned="$(git -C "${here}" ls-tree HEAD hul-trigger 2>/dev/null | awk '{print $3}')"
if [[ -n "${pinned}" && "${pinned}" != "${commit}" ]]; then
  echo "#E: ${src} is at ${commit}, the repository pins ${pinned}; run: git submodule update hul/trigger/hul-trigger" >&2; exit 4
fi
url="$(git -C "${src}" remote get-url origin)"

# Fresh copy every time: the address is compiled in, so nothing may be reused.
# Only the items made here are replaced; other files in out-dir are kept.
mkdir -p "${out}"
out="$(cd "${out}" && pwd)"
rm -rf "${out}/Makefile" "${out}/src" "${out}/include" "${out}/bin" "${out}/build-info.json"
cp -a "${src}/software/Makefile" "${src}/software/src" "${src}/software/include" "${out}/"
rm -rf "${out}/src/build"
cat > "${out}/include/TargetIP.hh" <<EOF
// -*- C++ -*-
// Generated by hul/trigger/build-tools.sh from HUL_TRIGGER_IP; do not edit.
#ifndef TARGET_IP_HH
#define TARGET_IP_HH

#include <string>

namespace config {
  const std::string kFpgaIp = "${ip}";
}

#endif
EOF
make -C "${out}" -j "$(nproc)" color=0 all

python3 - "${out}" "${commit}" "${ip}" "${url}" <<'PY'
import hashlib, json, pathlib, sys, time
out, commit, ip, url = pathlib.Path(sys.argv[1]), sys.argv[2], sys.argv[3], sys.argv[4]
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
info = {'source': url, 'commit': commit, 'board_ip': ip, 'built': time.strftime('%Y-%m-%dT%H:%M:%S%z'),
        'target_ip_header_sha256': sha(out / 'include' / 'TargetIP.hh'),
        'binaries': {p.name: sha(p) for p in sorted((out / 'bin').iterdir()) if p.is_file()}}
(out / 'build-info.json').write_text(json.dumps(info, indent=2) + '\n')
PY

echo "#D: hul-trigger ${commit} for ${ip} -> ${out}/bin"
sha256sum "${out}"/bin/*

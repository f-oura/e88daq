#!/usr/bin/env bash
# Build the HUL trigger control programs (Register, NimIO, Debug, ReconfigFPGA) from
# jparc-saphire/hul-trigger at the commit pinned in manifests/upstream.yaml.
#
# The upstream programs take the board address from include/TargetIP.hh at compile
# time. This script builds a copy of the pinned sources with that header generated
# from HUL_TRIGGER_IP, so the address stays in the host configuration and the pinned
# checkout stays clean. Rebuild after changing the address.
#
# Host side only: nothing here talks to a board.
#
# Usage: HUL_TRIGGER_IP=<board IPv4> build-tools.sh <work-dir>
#   (normally: set -a; . config/local/hul-trigger.env; set +a)
#   result: <work-dir>/hul-trigger/build/bin/*, <work-dir>/hul-trigger/build-info.json
# Needs: git, make, a C++17 compiler, zlib headers; network access to GitHub for the first clone.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
manifest="${root}/manifests/upstream.yaml"
pinned() { awk -v key="  $1:" '$0 == key {f=1} f && /commit:/ {print $2; exit}' "${manifest}"; }
url() { awk -v key="  $1:" '$0 == key {f=1} f && /url:/ {print $2; exit}' "${manifest}"; }

work_dir="${1:?usage: HUL_TRIGGER_IP=<board IPv4> $0 <work-dir>}"
ip="${HUL_TRIGGER_IP:?HUL_TRIGGER_IP is not set (see config/hul-trigger.env.example)}"
if ! [[ "${ip}" =~ ^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})$ ]] ||
   (( BASH_REMATCH[1] > 255 || BASH_REMATCH[2] > 255 || BASH_REMATCH[3] > 255 || BASH_REMATCH[4] > 255 )); then
  echo "#E: HUL_TRIGGER_IP is not an IPv4 address: ${ip}" >&2; exit 2
fi

mkdir -p "${work_dir}/hul-trigger"
work_dir="$(cd "${work_dir}" && pwd)"
commit="$(pinned hul-trigger)"
[[ -n "${commit}" ]] || { echo "#E: no pinned commit for hul-trigger in ${manifest}" >&2; exit 4; }
src="${work_dir}/hul-trigger/src"
build="${work_dir}/hul-trigger/build"

if [[ ! -d "${src}/.git" ]]; then
  git clone --quiet "$(url hul-trigger)" "${src}"
fi
git -C "${src}" fetch --quiet origin
git -C "${src}" checkout --quiet --detach "${commit}"
if [[ -n "$(git -C "${src}" status --porcelain)" ]]; then
  echo "#E: ${src} has local changes; refusing to build an unpinned tree" >&2; exit 4
fi
[[ "$(git -C "${src}" rev-parse HEAD)" == "${commit}" ]] || { echo "#E: ${src} is not at ${commit}" >&2; exit 4; }

# Fresh build copy every time: the address is compiled in, so nothing may be reused.
rm -rf "${build}"
mkdir -p "${build}"
cp -a "${src}/software/Makefile" "${src}/software/src" "${src}/software/include" "${build}/"
rm -rf "${build}/src/build"
cat > "${build}/include/TargetIP.hh" <<EOF
// -*- C++ -*-
// Generated by hul/trigger/build-tools.sh from HUL_TRIGGER_IP; do not edit.
#ifndef TARGET_IP_HH
#define TARGET_IP_HH

#include <string>

namespace config {
  const std::string kFpgaIp = "${ip}";
}

#endif
EOF
make -C "${build}" -j "$(nproc)" color=0 all

python3 - "${build}" "${commit}" "${ip}" "$(url hul-trigger)" <<'PY'
import hashlib, json, pathlib, sys, time
build, commit, ip, url = pathlib.Path(sys.argv[1]), sys.argv[2], sys.argv[3], sys.argv[4]
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
info = {'source': url, 'commit': commit, 'board_ip': ip, 'built': time.strftime('%Y-%m-%dT%H:%M:%S%z'),
        'target_ip_header_sha256': sha(build / 'include' / 'TargetIP.hh'),
        'binaries': {p.name: sha(p) for p in sorted((build / 'bin').iterdir()) if p.is_file()}}
(build.parent / 'build-info.json').write_text(json.dumps(info, indent=2) + '\n')
PY

echo "#D: hul-trigger ${commit} for ${ip} -> ${build}/bin"
sha256sum "${build}"/bin/*
